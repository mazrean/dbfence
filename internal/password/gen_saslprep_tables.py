#!/usr/bin/env python3
"""Generate saslprep_tables.go from the RFC 3454 tables.

Python's stringprep module implements the RFC 3454 tables on top of the
Unicode 3.2 database, which is exactly what PostgreSQL's pg_saslprep uses.

Usage: python3 gen_saslprep_tables.py > saslprep_tables.go && gofmt -w saslprep_tables.go
"""

import stringprep as sp

TABLES = [
    ("unassignedRanges", "RFC 3454 A.1: code points unassigned in Unicode 3.2.", [sp.in_table_a1]),
    ("mappedToNothingRanges", "RFC 3454 B.1: commonly mapped to nothing.", [sp.in_table_b1]),
    ("nonASCIISpaceRanges", "RFC 3454 C.1.2: non-ASCII space characters.", [sp.in_table_c12]),
    (
        "prohibitedRanges",
        "RFC 4013 section 2.3: RFC 3454 C.1.2, C.2.1, C.2.2 and C.3 to C.9.",
        [
            sp.in_table_c12, sp.in_table_c21, sp.in_table_c22, sp.in_table_c3, sp.in_table_c4,
            sp.in_table_c5, sp.in_table_c6, sp.in_table_c7, sp.in_table_c8, sp.in_table_c9,
        ],
    ),
    ("randALCatRanges", "RFC 3454 D.1: characters with bidirectional property R or AL.", [sp.in_table_d1]),
    ("lCatRanges", "RFC 3454 D.2: characters with bidirectional property L.", [sp.in_table_d2]),
]


def ranges(preds):
    out, start = [], None
    for cp in range(0x110000):
        c = chr(cp)
        hit = any(p(c) for p in preds)
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


print("// Code generated by gen_saslprep_tables.py; DO NOT EDIT.")
print()
print("package password")
for name, doc, preds in TABLES:
    print()
    print(f"// {name} lists {doc}")
    print(f"var {name} = []runeRange{{")
    for lo, hi in ranges(preds):
        print(f"\t{{0x{lo:04X}, 0x{hi:04X}}},")
    print("}")
